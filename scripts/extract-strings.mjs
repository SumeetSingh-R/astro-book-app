// Builds the translation catalogue: every English string the web app shows.
// It reads the source for t('…') and msg('…') calls, so the list never has to be kept by hand.
// Usage: node scripts/extract-strings.mjs   (runs as part of `npm run build`)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : /\.(jsx?|mjs)$/.test(e.name) ? [join(dir, e.name)] : []));

const CALL = /(?<![\w.])(?:t|msg)\(\s*('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\$]|\\.)*`)/g;
const found = new Set();
for (const file of walk(join(root, 'web/src'))) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(CALL)) {
    const text = new Function(`return ${m[1]};`)(); // a string literal from our own source
    if (/\p{L}/u.test(text)) found.add(text);
  }
}
// Proper names come from the engine's own tables.
for (const name of (await import('../i18n/names.mjs')).default) found.add(name);
const catalog = [...found].sort((a, b) => a.localeCompare(b, 'en'));
const version = createHash('sha1').update(JSON.stringify(catalog)).digest('hex').slice(0, 10);

mkdirSync(join(root, 'i18n'), { recursive: true });
writeFileSync(join(root, 'i18n/catalog.mjs'), `// Generated by scripts/extract-strings.mjs. Do not edit by hand.\nexport default ${JSON.stringify(catalog, null, 1)};\n`);
writeFileSync(join(root, 'i18n/version.mjs'), `// Generated by scripts/extract-strings.mjs. Changes whenever the interface text changes.\nexport const CATALOG_VERSION = '${version}';\n`);
console.log(`Translation catalogue: ${catalog.length} strings, version ${version}.`);
