// Builds the place-lookup dataset used by /api/places.
// Source: GeoNames cities with population > 1000 (via the `all-the-cities` package),
// with the IANA timezone derived from coordinates (via `tz-lookup`).
// Output: api/data/places.generated.mjs  (compact rows: [name, country, admin, lat, lon, population, tzIndex])
import { createRequire } from 'node:module';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const cities = require('all-the-cities');
const tzlookup = require('tz-lookup');

const ascii = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '');
const tzList = [];
const tzIndex = new Map();
const rows = [];

for (const c of cities) {
  const [lon, lat] = c.loc.coordinates;
  let tz;
  try { tz = tzlookup(lat, lon); } catch { continue; }
  if (!tzIndex.has(tz)) { tzIndex.set(tz, tzList.length); tzList.push(tz); }
  rows.push([
    ascii(c.name), c.country, c.adminCode || '',
    Math.round(lat * 1e4) / 1e4, Math.round(lon * 1e4) / 1e4,
    c.population || 0, tzIndex.get(tz),
  ]);
}
rows.sort((a, b) => b[5] - a[5]); // most populous first, so early matches are the likely ones

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'api', 'data');
mkdirSync(outDir, { recursive: true });
const body = `// GENERATED by scripts/build-places.mjs - do not edit.\nexport default ${JSON.stringify({ tz: tzList, rows })};\n`;
writeFileSync(join(outDir, 'places.generated.mjs'), body);
console.log(`places: ${rows.length} rows, ${tzList.length} timezones, ${(body.length / 1e6).toFixed(1)} MB`);
